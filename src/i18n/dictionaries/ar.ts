/** Wraps LTR content (an ISO date, a Latin store/product name) in Unicode
 * directional-isolate marks so it doesn't get visually reordered when embedded
 * inline inside an Arabic (RTL) sentence — e.g. "2026-09-09" rendering as
 * "09-09-2026" once surrounded by Arabic words on both sides. */
function ltr(value: string) {
  return `⁦${value}⁩`;
}

